#ifndef MAP_32BIT
#define MAP_32BIT 0x40
#endif

extern "C" {
    #include "/tmp/openblas_build/cblas.h"
    void openblas_set_num_threads(int num_threads);

    // Function generated by Y Compiler CLI from tests/y_cpu_matmul.ysu
    void y_cpu_matmul_kernel(const float* A, const float* B, float* C, int M, int N, int K);
}

inline void do_not_optimize(void* ptr) {
    asm volatile("" : : "g"(ptr) : "memory");
}

void openblas_reference_gemm(const float* A, const float* B, float* C, int M, int N, int K) {
    cblas_sgemm(CblasRowMajor, CblasNoTrans, CblasNoTrans,
                M, N, K,
                1.0f, A, K,
                B, N,
                0.0f, C, N);
}

float* alloc_32bit_buffer(size_t elements) {
    size_t bytes = elements * sizeof(float);
    void* ptr = mmap(NULL, bytes, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_32BIT, -1, 0);
    if (ptr == MAP_FAILED) {
        ptr = malloc(bytes);
    }
    return (float*)ptr;
}

void free_32bit_buffer(float* ptr, size_t elements) {
    munmap(ptr, elements * sizeof(float));
}

struct BenchmarkResult {
    std::string regime_name;
    int M, N, K;
    double y_time_us;
    double openblas_time_us;
    double y_gflops;
    double openblas_gflops;
    double ratio;
    bool output_matched;
};

BenchmarkResult run_benchmark(
    const std::string& name,
    int M, int N, int K,
    int warmup_iters = 2,
    int bench_iters = 5
) {
    float* A = alloc_32bit_buffer(M * K);
    float* B = alloc_32bit_buffer(K * N);
    float* C_y = alloc_32bit_buffer(M * N);
    float* C_openblas = alloc_32bit_buffer(M * N);

    std::mt19937 rng(42);
    std::uniform_real_distribution<float> dist(-1.0f, 1.0f);
    for (size_t i = 0; i < M * K; ++i) A[i] = dist(rng);
    for (size_t i = 0; i < K * N; ++i) B[i] = dist(rng);

    y_cpu_matmul_kernel(A, B, C_y, M, N, K);
    openblas_reference_gemm(A, B, C_openblas, M, N, K);
    
    double max_diff = 0.0;
    for (size_t idx = 0; idx < M * N; ++idx) {
        max_diff = std::max(max_diff, (double)std::abs(C_y[idx] - C_openblas[idx]));
    }
    bool matched = max_diff < 1e-1;

    // Benchmark REAL Y Compiler Output Binary
    for (int i = 0; i < warmup_iters; ++i) {
        y_cpu_matmul_kernel(A, B, C_y, M, N, K);
        do_not_optimize(C_y);
    }

    auto start_y = std::chrono::high_resolution_clock::now();
    for (int i = 0; i < bench_iters; ++i) {
        y_cpu_matmul_kernel(A, B, C_y, M, N, K);
        do_not_optimize(C_y);
    }
    auto end_y = std::chrono::high_resolution_clock::now();
    double y_us = std::chrono::duration<double, std::micro>(end_y - start_y).count() / bench_iters;

    // Benchmark REAL OpenBLAS Library
    for (int i = 0; i < warmup_iters; ++i) {
        openblas_reference_gemm(A, B, C_openblas, M, N, K);
        do_not_optimize(C_openblas);
    }

    auto start_openblas = std::chrono::high_resolution_clock::now();
    for (int i = 0; i < bench_iters; ++i) {
        openblas_reference_gemm(A, B, C_openblas, M, N, K);
        do_not_optimize(C_openblas);
    }
    auto end_openblas = std::chrono::high_resolution_clock::now();
    double openblas_us = std::chrono::duration<double, std::micro>(end_openblas - start_openblas).count() / bench_iters;

    double total_flops = 2.0 * M * N * K;
    double y_gflops = (total_flops / (y_us * 1e-6)) / 1e9;
    double openblas_gflops = (total_flops / (openblas_us * 1e-6)) / 1e9;
    double ratio = openblas_us / y_us;

    free_32bit_buffer(A, M * K);
    free_32bit_buffer(B, K * N);
    free_32bit_buffer(C_y, M * N);
    free_32bit_buffer(C_openblas, M * N);

    return { name, M, N, K, y_us, openblas_us, y_gflops, openblas_gflops, ratio, matched };
}

void print_suite(const std::string& title, int threads) {
    omp_set_num_threads(threads);
    openblas_set_num_threads(threads);

    std::cout << "\n===============================================================" << std::endl;
    std::cout << " " << title << " (" << threads << " THREADS)" << std::endl;
    std::cout << "===============================================================" << std::endl;

    std::vector<BenchmarkResult> results;
    results.push_back(run_benchmark("SmallDirect (L1 Cache)", 16, 16, 16, 5, 20));
    results.push_back(run_benchmark("MediumSquare", 128, 128, 128, 2, 5));
    results.push_back(run_benchmark("NiceSquare (Large Square)", 256, 256, 256, 1, 3));

    std::cout << std::left 
              << std::setw(28) << "Regime / Shape"
              << std::setw(16) << "Dimensions"
              << std::setw(14) << "Y CLI (us)"
              << std::setw(18) << "OpenBLAS Time (us)"
              << std::setw(14) << "Y CLI GFLOPS"
              << std::setw(16) << "OpenBLAS GFLOPS"
              << std::setw(10) << "Match?"
              << std::setw(14) << "Ratio (OB/Y)"
              << std::endl;
    std::cout << std::string(128, '-') << std::endl;

    for (const auto& r : results) {
        std::string dim_str = std::to_string(r.M) + "x" + std::to_string(r.N) + "x" + std::to_string(r.K);
        std::cout << std::left
                  << std::setw(28) << r.regime_name
                  << std::setw(16) << dim_str
                  << std::setw(14) << std::fixed << std::setprecision(2) << r.y_time_us
                  << std::setw(18) << std::fixed << std::setprecision(2) << r.openblas_time_us
                  << std::setw(14) << std::fixed << std::setprecision(2) << r.y_gflops
                  << std::setw(16) << std::fixed << std::setprecision(2) << r.openblas_gflops
                  << std::setw(10) << (r.output_matched ? "YES" : "NO")
                  << std::setw(14) << std::fixed << std::setprecision(2) << r.ratio << "x"
                  << std::endl;
    }
    std::cout << "===============================================================" << std::endl;
}

int main() {
    print_suite("REAL Y COMPILER CLI BENCHMARK", 1);
    return 0;
}
