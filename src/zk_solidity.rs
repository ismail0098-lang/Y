use crate::mini_json::{Json, P};

/// Reads a snarkjs `verification_key.json` into a [`Groth16VerifyingKey`].
///
/// snarkjs stores G1 as `[x, y, z]` and G2 as `[[x_c0, x_c1], [y_c0, y_c1],
/// [z_c0, z_c1]]` - affine with a trailing `z` of 1 that is dropped here, and
/// the `Fq2` pairs already in `(c0, c1)` order, which is the order this module
/// wants. The EVM swap happens once, at emission.
///
/// `protocol` and `curve` are checked rather than assumed. A PLONK or
/// BLS12-381 key has the same field names and would otherwise produce a
/// confident, deployable, permanently-broken verifier.
pub fn parse_snarkjs_vkey(json: &str) -> Result<Groth16VerifyingKey, String> {
    let root = P { b: json.as_bytes(), i: 0 }.value()?;

    if let Some(Json::Str(p)) = root.get("protocol") {
        if p != "groth16" {
            return Err(format!(
                "verification key is for protocol {:?}; this generator emits a Groth16 verifier \
                 and would produce a contract that can never verify anything for {:?}",
                p, p
            ));
        }
    }
    if let Some(Json::Str(c)) = root.get("curve") {
        let c_lower = c.to_lowercase();
        if c_lower != "bn128" && c_lower != "bn254" && c_lower != "altbn128" {
            return Err(format!(
                "verification key is over curve {:?}; the EVM precompiles at 0x06/0x07/0x08 \
                 implement BN254 only",
                c
            ));
        }
    }

    let g1 = |key: &str| -> Result<[String; 2], String> {
        let a = root
            .get(key)
            .and_then(Json::arr)
            .ok_or_else(|| format!("missing or malformed {:?}", key))?;
        if a.len() < 2 {
            return Err(format!("{:?} needs at least x and y", key));
        }
        Ok([
            a[0].scalar().ok_or_else(|| format!("{:?}.x is not a scalar", key))?,
            a[1].scalar().ok_or_else(|| format!("{:?}.y is not a scalar", key))?,
        ])
    };

    let g2 = |key: &str| -> Result<[[String; 2]; 2], String> {
        let a = root
            .get(key)
            .and_then(Json::arr)
            .ok_or_else(|| format!("missing or malformed {:?}", key))?;
        if a.len() < 2 {
            return Err(format!("{:?} needs at least x and y", key));
        }
        let pair = |j: &Json, what: &str| -> Result<[String; 2], String> {
            let v = j.arr().ok_or_else(|| format!("{:?}.{} is not a pair", key, what))?;
            if v.len() < 2 {
                return Err(format!("{:?}.{} needs both Fq2 coefficients", key, what));
            }
            Ok([
                v[0].scalar().ok_or_else(|| format!("{:?}.{}.c0 is not a scalar", key, what))?,
                v[1].scalar().ok_or_else(|| format!("{:?}.{}.c1 is not a scalar", key, what))?,
            ])
        };
        Ok([pair(&a[0], "x")?, pair(&a[1], "y")?])
    };

    let ic_raw = root
        .get("IC")
        .and_then(Json::arr)
        .ok_or("missing or malformed \"IC\"")?;
    let mut ic = Vec::with_capacity(ic_raw.len());
    for (i, p) in ic_raw.iter().enumerate() {
        let v = p.arr().ok_or_else(|| format!("IC[{}] is not a point", i))?;
        if v.len() < 2 {
            return Err(format!("IC[{}] needs x and y", i));
        }
        ic.push([
            v[0].scalar().ok_or_else(|| format!("IC[{}].x is not a scalar", i))?,
            v[1].scalar().ok_or_else(|| format!("IC[{}].y is not a scalar", i))?,
        ]);
    }
    if ic.is_empty() {
        return Err("\"IC\" is empty; a Groth16 key always has at least one point".into());
    }

    let vk = Groth16VerifyingKey {
        alpha_g1: g1("vk_alpha_1")?,
        beta_g2: g2("vk_beta_2")?,
        gamma_g2: g2("vk_gamma_2")?,
        delta_g2: g2("vk_delta_2")?,
        ic,
    };

    // Cross-check against the key's own claim, when it makes one.
    if let Some(n) = root.get("nPublic").and_then(Json::scalar) {
        if let Ok(n) = n.parse::<usize>() {
            if n != vk.num_public_inputs() {
                return Err(format!(
                    "key says nPublic = {} but IC has {} points (expected {})",
                    n,
                    vk.ic.len(),
                    n + 1
                ));
            }
        }
    }
    Ok(vk)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn dummy_vk(n_public: usize) -> Groth16VerifyingKey {
        let g2 = |a: &str, b: &str, c: &str, d: &str| {
            [[a.to_string(), b.to_string()], [c.to_string(), d.to_string()]]
        };
        Groth16VerifyingKey {
            alpha_g1: ["1".into(), "2".into()],
            beta_g2: g2("3", "4", "5", "6"),
            gamma_g2: g2("7", "8", "9", "10"),
            delta_g2: g2("11", "12", "13", "14"),
            ic: (0..=n_public)
                .map(|i| [format!("{}", 100 + i), format!("{}", 200 + i)])
                .collect(),
        }
    }

    /// The swap is the whole point, so assert on it directly rather than
    /// trusting that a downstream test would notice.
    #[test]
    fn g2_constants_are_emitted_imaginary_part_first() {
        let src = emit_groth16_verifier(&dummy_vk(1), "V");
        // beta_g2 went in as [[3, 4], [5, 6]] and must come out [4, 3], [6, 5].
        assert!(
            src.contains("vk.beta2 = Pairing.G2Point(\n            [4, 3],\n            [6, 5]\n        );"),
            "beta2 was not swapped into EVM order:\n{}",
            src
        );
    }

    #[test]
    fn input_array_is_sized_to_the_public_inputs() {
        for n in [1usize, 2, 5] {
            let src = emit_groth16_verifier(&dummy_vk(n), "V");
            assert!(src.contains(&format!("uint[{}] memory input", n)));
            assert!(src.contains(&format!("vk.IC = new Pairing.G1Point[]({});", n + 1)));
        }
    }

    #[test]
    fn contract_name_is_honoured() {
        let src = emit_groth16_verifier(&dummy_vk(1), "MyCircuitVerifier");
        assert!(src.contains("contract MyCircuitVerifier {"));
    }

    const SNARKJS_VKEY: &str = r#"{
     "protocol": "groth16",
     "curve": "bn128",
     "nPublic": 2,
     "vk_alpha_1": ["11","12","1"],
     "vk_beta_2": [["21","22"],["23","24"],["1","0"]],
     "vk_gamma_2": [["31","32"],["33","34"],["1","0"]],
     "vk_delta_2": [["41","42"],["43","44"],["1","0"]],
     "vk_alphabeta_12": [[["9","9"],["9","9"],["9","9"]]],
     "IC": [["51","52","1"],["53","54","1"],["55","56","1"]]
    }"#;

    #[test]
    fn reads_a_snarkjs_verification_key() {
        let vk = parse_snarkjs_vkey(SNARKJS_VKEY).expect("parse");
        assert_eq!(vk.num_public_inputs(), 2);
        assert_eq!(vk.alpha_g1, ["11".to_string(), "12".to_string()]);
        // snarkjs stores Fq2 as (c0, c1); we keep that order and swap on emit.
        assert_eq!(vk.beta_g2[0], ["21".to_string(), "22".to_string()]);
        assert_eq!(vk.ic.len(), 3);
        assert_eq!(vk.ic[2], ["55".to_string(), "56".to_string()]);

        let src = emit_groth16_verifier(&vk, "V");
        assert!(src.contains("[22, 21]"), "beta2.x should be swapped on emit");
        assert!(src.contains("uint[2] memory input"));
    }

    /// A key for another proof system has the same field names and would
    /// otherwise yield a deployable contract that can never verify anything.
    #[test]
    fn rejects_a_non_groth16_or_non_bn254_key() {
        let plonk = SNARKJS_VKEY.replace("groth16", "plonk");
        let err = parse_snarkjs_vkey(&plonk).expect_err("plonk key must be refused");
        assert!(err.contains("plonk"), "error should name the protocol: {}", err);

        let bls = SNARKJS_VKEY.replace("bn128", "bls12381");
        let err = parse_snarkjs_vkey(&bls).expect_err("bls12-381 key must be refused");
        assert!(err.contains("BN254"), "error should name the supported curve: {}", err);
    }

    /// `nPublic` disagreeing with `IC` means the file is not internally
    /// consistent; guessing which one is right would size `verifyProof`'s input
    /// array wrongly and break every call.
    #[test]
    fn rejects_inconsistent_public_input_count() {
        let bad = SNARKJS_VKEY.replace("\"nPublic\": 2", "\"nPublic\": 5");
        let err = parse_snarkjs_vkey(&bad).expect_err("must reject");
        assert!(err.contains("nPublic"), "{}", err);
    }
}
